"""Package evaluation run artifacts into a single ZIP archive for MEXT interview.

Produces a timestamped ZIP containing config.yaml, seed.txt, splits/, plots/,
models/, mext_demo.html, and README.txt with reproduction instructions.

Usage:
    python -m scripts.package_results
    python -m scripts.package_results --run-path ml/eval/runs/20260525_204307
    python -m scripts.package_results --output-dir ./packages --zip-name mext_package.zip
"""

import argparse
import logging
import os
import re
import shutil
import sys
import tempfile
import zipfile
from datetime import datetime, timezone
from pathlib import Path

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
)
logger = logging.getLogger(__name__)

try:
    import yaml
except ImportError:
    yaml = None
    logger.warning("PyYAML not available — cannot read config.yaml for README")


def generate_readme(config: dict, run_path: str) -> str:
    """Generate plain-text README with reproduction instructions."""
    seed = config.get("seed", "N/A")
    cold_ratio = config.get("cold_ratio", "N/A")
    k_values = config.get("k_values", [10])
    split_strategy = config.get("split_strategy", "N/A")
    evaluation_mode = config.get("evaluation_mode", "N/A")
    graphsage_epochs = config.get("graphsage_epochs", "N/A")
    graphsage_embedding_dim = config.get("graphsage_embedding_dim", "N/A")
    generation_date = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    return f"""=================================================================
MEXT Demo — Cold-Start Recommendation Research
Reproducible Results Package
=================================================================

Package generated: {generation_date}

-- Overview --
This package contains evaluation results for cold-start fragrance
recommendation using GraphSAGE with two graph construction strategies:
embedding-derived KNN (circular, flawed) and Jaccard note-overlap
(structurally independent, fixed). The central finding is that graph
construction methodology — not model architecture — determines GNN
cold-start performance.

-- Contents --
config.yaml              - Evaluation configuration (seed, cold_ratio, k_values, etc.)
seed.txt                 - Random seed used for reproducibility
splits/warm_items.csv    - Warm items (with interaction history)
splits/cold_items.csv    - Cold items (zero interactions - held out)
plots/                   - Result visualizations
models/                  - GraphSAGE checkpoints and embeddings:
  - graphsage_model.pt     Trained GraphSAGE-Embedding (embedding KNN graph)
  - graphsage_jaccard.pt   Trained GraphSAGE-Jaccard (Jaccard note graph)
  - node_embeddings.npy    All node embeddings (4559 x 64)
  - edge_index.npy         Graph edge index
  - node_ids.json          Node ID mapping
mext_demo.html           - Self-contained demo page (open in any browser)

-- Key Parameters --
Seed:        {seed}
Cold ratio:  {cold_ratio}
k_values:    {k_values}
Strategy:    {split_strategy}
Mode:        {evaluation_mode}
GraphSAGE:   {graphsage_epochs} epochs, {graphsage_embedding_dim}-dim hidden embeddings

-- Reproduction Steps --

1. Requirements:
   - Python 3.10+
   - Dependencies: pip install -r requirements.txt
   - (or use the project's virtual environment)

   2. Run pure cold-start evaluation with the canonical seed:
       python -m ml.eval.pipeline --mode pure_cold --seed 42

   This reproduces all six model evaluations (GraphSAGE-Jaccard,
   GraphSAGE-Embedding, Feature-Only, Content-Only oracle, Popularity, Random),
   the Jaccard threshold sweep, and the stratification grid.

3. Regenerate the demo page:
   python -m scripts.generate_demo --run-path {run_path}

4. View results:
   Open {run_path}/mext_demo.html in any modern browser (no server required).

-- Important Caveats ---

1. Feature circularity (GraphSAGE-Embedding):
   The embedding-derived KNN graph shares its feature space with node features.
   GraphSAGE trained on this graph performs 63% worse than simple feature
   cosine similarity (NDCG 0.197 vs 0.557). This is the central finding —
   a negative result documenting a failure mode in graph construction.

2. Synthetic ground-truth methodology:
   Relevance is defined by primary-accord match + Jaccard(notes) > 0.20, NOT
   by actual user preference data. Results measure graph reconstruction
   accuracy for chemically similar fragrances — not human-perceived
   recommendation quality. GraphSAGE-Jaccard (NDCG 0.504) does NOT
   statistically beat Feature-Only (0.557, p=1.000, d=-0.149). The graph
   claim is scoped to structural independence, not absolute performance.

-- Reference --
Generated by Scentrix Evaluation Pipeline — Phase 6 (MEXT Demo)
Date: {generation_date}
"""


def package_results(run_path: str, output_dir: str = ".", zip_name: str = None) -> str:
    """Package evaluation run artifacts into a single ZIP archive.

    Args:
        run_path: Path to the evaluation run directory.
        output_dir: Directory to write the ZIP file.
        zip_name: Custom ZIP filename. If None, auto-generates.

    Returns:
        Path to the created ZIP archive.
    """
    run_dir = Path(run_path)
    if not run_dir.is_dir():
        raise NotADirectoryError(f"Run directory not found: {run_dir}")

    logger.info("Packaging evaluation run: %s", run_dir.resolve())

    # Load config
    config_path = run_dir / "config.yaml"
    config = {}
    if config_path.is_file() and yaml:
        with open(config_path) as f:
            config = yaml.safe_load(f)
        logger.info("Config loaded: seed=%s, cold_ratio=%s", config.get("seed"), config.get("cold_ratio"))
    elif config_path.is_file():
        logger.warning("PyYAML not installed — reading config as fallback")
        with open(config_path) as f:
            for line in f:
                if ":" in line:
                    k, v = line.split(":", 1)
                    config[k.strip()] = v.strip()
    else:
        logger.warning("No config.yaml found in %s", run_dir)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    if zip_name is None:
        zip_name = f"mext_demo_package_{timestamp}.zip"

    output_path = Path(output_dir) / zip_name
    output_path = output_path.resolve()
    Path(output_dir).mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)

        # 1. Copy config.yaml
        if config_path.is_file():
            shutil.copy2(config_path, tmp_path / "config.yaml")
            logger.info("Packaged: config.yaml")
        else:
            (tmp_path / "config.yaml").write_text("# No configuration found\n")

        # 2. Write seed.txt
        seed = config.get("seed", "N/A")
        (tmp_path / "seed.txt").write_text(f"Seed: {seed}\n")
        logger.info("Packaged: seed.txt (seed=%s)", seed)

        # 3. Copy splits/
        splits_dir = run_dir / "splits"
        if splits_dir.is_dir():
            shutil.copytree(splits_dir, tmp_path / "splits", dirs_exist_ok=True)
            csv_count = len(list((tmp_path / "splits").glob("*.csv")))
            logger.info("Packaged: splits/ (%d CSV files)", csv_count)
        else:
            (tmp_path / "splits").mkdir()
            (tmp_path / "splits" / "README.txt").write_text(
                "No split files were generated for this evaluation run.\n"
            )
            logger.warning("No splits/ directory found")

        # 4. Copy plots/
        plots_dir = run_dir / "plots"
        if plots_dir.is_dir() and any(plots_dir.iterdir()):
            shutil.copytree(plots_dir, tmp_path / "plots", dirs_exist_ok=True)
            plot_count = len(list((tmp_path / "plots").glob("*.png")))
            logger.info("Packaged: plots/ (%d PNG files)", plot_count)
        else:
            (tmp_path / "plots").mkdir()
            (tmp_path / "plots" / "README.txt").write_text(
                "No plots were generated for this evaluation run.\n"
                "Run the evaluation pipeline with reporting enabled to generate plots."
            )
            logger.info("No plots to package")

        # 5. Copy models/ (if exists and has files)
        models_dir = run_dir / "models"
        if models_dir.is_dir() and any(models_dir.iterdir()):
            model_dir = tmp_path / "models"
            model_dir.mkdir(exist_ok=True)
            model_count = 0
            for f in models_dir.iterdir():
                if f.is_file() and not f.name.startswith("."):
                    shutil.copy2(f, model_dir / f.name)
                    model_count += 1
            logger.info("Packaged: models/ (%d files)", model_count)
        else:
            (tmp_path / "models").mkdir(exist_ok=True)
            (tmp_path / "models" / "README.txt").write_text(
                "Model artifacts are not available for this evaluation run.\n"
                "The run may not have used GraphSAGE, or model persistence was not enabled."
            )
            logger.info("No models to package")

        # 6. Copy mext_demo.html (if exists)
        demo_html = run_dir / "mext_demo.html"
        if demo_html.is_file():
            shutil.copy2(demo_html, tmp_path / "mext_demo.html")
            size_kb = demo_html.stat().st_size / 1024
            logger.info("Packaged: mext_demo.html (%.1f KB)", size_kb)
        else:
            (tmp_path / "DEMO_NOT_GENERATED.md").write_text(
                "# Demo Page Not Generated\n\n"
                f"The mext_demo.html was not found in {run_dir}.\n"
                "Run `python -m scripts.generate_demo --run-path {run_dir}` first.\n"
            )
            logger.warning("No mext_demo.html found — created DEMO_NOT_GENERATED.md")

        # 7. Write README.txt
        readme = generate_readme(config, str(run_dir))
        (tmp_path / "README.txt").write_text(readme)
        logger.info("Packaged: README.txt")

        # Create ZIP
        with zipfile.ZipFile(str(output_path), "w", zipfile.ZIP_DEFLATED) as zf:
            for file_path in sorted(tmp_path.rglob("*")):
                if file_path.is_file():
                    arcname = str(file_path.relative_to(tmp_path))
                    zf.write(str(file_path), arcname)

    logger.info("ZIP archive created: %s", output_path)

    # Print summary
    with zipfile.ZipFile(str(output_path), "r") as zf:
        names = zf.namelist()
        print(f"\nPackage created: {output_path}")
        print(f"Total files: {len(names)}")
        print(f"Contents:")
        for name in sorted(names):
            info = zf.getinfo(name)
            print(f"  {name:50s} {info.file_size:>8d} bytes")

    return str(output_path)


def find_latest_run(base_dir: str = "ml/eval/runs") -> str:
    """Find the latest timestamp-format directory under runs/."""
    runs_dir = Path(base_dir)
    if not runs_dir.is_dir():
        raise FileNotFoundError(f"Runs directory not found: {runs_dir}")

    run_dirs = sorted(
        [d for d in runs_dir.iterdir() if d.is_dir() and re.match(r"^\d{8}_\d{6}$", d.name)],
        reverse=True,
    )
    if not run_dirs:
        raise FileNotFoundError(f"No timestamped run directories found under {runs_dir}")
    return str(run_dirs[0])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Package MEXT demo results into a reproducible ZIP archive",
    )
    parser.add_argument(
        "--run-path",
        type=str,
        default=None,
        help="Path to evaluation run directory (default: latest timestamp dir under ml/eval/runs/)",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default=".",
        help="Output directory for the ZIP archive (default: current directory)",
    )
    parser.add_argument(
        "--zip-name",
        type=str,
        default=None,
        help="Custom ZIP filename (default: auto-generated mext_demo_package_{timestamp}.zip)",
    )
    parser.add_argument(
        "--verbose", "-v",
        action="store_true",
        help="Print debug information",
    )
    args = parser.parse_args()

    if args.verbose:
        logging.getLogger().setLevel(logging.DEBUG)

    try:
        run_path = args.run_path or find_latest_run()
        output_path = package_results(
            run_path=run_path,
            output_dir=args.output_dir,
            zip_name=args.zip_name,
        )
        print(f"\nDone: {output_path}")
    except (FileNotFoundError, NotADirectoryError) as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        logger.error("Packaging failed: %s", e)
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
